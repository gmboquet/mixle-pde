"""Frozen capability and limitation inventory for mixle-pde's legacy solver kernels.

mixle-pde is the compatibility facade over mixle's legacy PDE/ODE numerical kernels (``fem.py``,
``gas_dynamics.py``, ``geophysics.py``, ``monitoring_design.py``, ``posterior_query.py``,
``geo_observations.py``, and the rest of ``mixle_pde/``). ``mixle_pde.problem_adapter.PDEBackendProfile``
lets a caller declare a capability profile in the *abstract*; this module is the companion fact base --
what the kernels that already exist can *actually* do today, one entry per public top-level module, along
nine axes: method, dimension, cell/grid type, boundary-condition support, differentiability, complex
support, steady/transient status, parallel status, and verification level.

Methodology and honesty notes
------------------------------
* This is a frozen SNAPSHOT of current capability, not a target or a promise. A green test proves the
  linear algebra ran; it is not, by itself, evidence the physics is correct -- ``verification_level``
  records only what the existing test suite checks today, never an independent physical validation.
* ``differentiable`` is a conservative static proxy: True means the module imports ``torch`` for at
  least one primary compute path (an autograd-capable route exists somewhere in it). It is not a
  per-function proof that every symbol in the module is differentiable end to end.
* ``complex_support`` means the module uses a complex dtype or the literal imaginary unit somewhere in
  its primary compute path (frequency-domain / spectral methods, mostly).
* ``parallel_status`` is ``"single_process"`` for every entry: a repo-wide sweep found no ``mpi4py``,
  no ``multiprocessing``, and no ``concurrent.futures``/``joblib`` usage anywhere under ``mixle_pde/``.
  Vectorized NumPy/Torch operations are the only concurrency mixle-pde has today; distributed/MPI
  execution is explicitly future (production-backend) work per the mixle-pde work plan's ADR-3, not
  something this inventory should imply exists.
* Non-solver modules (Bayesian posterior utilities, likelihood models, environmental data loaders,
  infrastructure/glue code) are inventoried too -- ``is_solver=False`` and the PDE-specific axes
  (``dimension``, ``grid_type``, ``boundary_conditions``, ``time_regime``) read ``"not_applicable"``
  for them, rather than being silently omitted, per the "unsupported features are explicit" bar.
* ``public_symbols`` lists every top-level, non-underscore class/function actually defined in the
  module (not merely re-exported elsewhere). ``tests/capability_inventory_test.py`` import-sweeps every
  module in this registry and asserts each listed symbol is real and every module file on disk is
  registered -- the mechanical half of the MP-A1 acceptance criterion. The categorical judgement calls
  (dimension, grid type, BC support, time regime, verification level) are the human-reviewed half,
  derived from each module's own docstrings/boundary-handling code and its associated tests; see the
  PR description for the review method.

Source: notes/mixle-pde-ai-native-multiphysics-work-plan.md section 8, MP-A1.
"""

