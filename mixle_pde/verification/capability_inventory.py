    """Capability/limitation record for one public ``mixle_pde`` top-level module."""

    module: str
    category: str
    is_solver: bool
    method: str
    dimension: tuple[str, ...]
    grid_type: str
    boundary_conditions: tuple[str, ...]
    differentiable: bool
    complex_support: bool
    time_regime: str
    parallel_status: str
    verification_level: str
    public_symbols: tuple[str, ...]
    limitations: tuple[str, ...] = ()

    def as_dict(self) -> dict[str, Any]:
        data = asdict(self)
        for key in ("dimension", "boundary_conditions", "public_symbols", "limitations"):
            data[key] = list(data[key])
        return data


