_BY_MODULE: dict[str, SolverProfile] = {profile.module: profile for profile in CAPABILITY_INVENTORY}

if len(_BY_MODULE) != len(CAPABILITY_INVENTORY):
    raise AssertionError("duplicate module entries in CAPABILITY_INVENTORY")


def get_profile(module: str) -> SolverProfile:
    """Look up a profile by its fully-qualified module name, e.g. ``"mixle_pde.fem"``."""
    try:
        return _BY_MODULE[module]
    except KeyError as exc:
        raise KeyError(f"no capability_inventory entry for module {module!r}") from exc


def modules() -> tuple[str, ...]:
    """Every module name registered in the inventory, in registry order."""
    return tuple(profile.module for profile in CAPABILITY_INVENTORY)


def solver_profiles() -> tuple[SolverProfile, ...]:
    """Only the entries that are themselves discretized PDE/ODE solvers (``is_solver=True``)."""
    return tuple(profile for profile in CAPABILITY_INVENTORY if profile.is_solver)


def by_category() -> dict[str, tuple[SolverProfile, ...]]:
    """Group registered profiles by their ``category`` label."""
    grouped: dict[str, list[SolverProfile]] = {}
    for profile in CAPABILITY_INVENTORY:
        grouped.setdefault(profile.category, []).append(profile)
    return {category: tuple(profiles) for category, profiles in grouped.items()}


def to_capability_matrix() -> dict[str, Any]:
    """Machine-readable dict form -- the exact shape serialized to ``docs/capability-matrix.json``."""
    return {
        "schema_version": 1,
        "source": "mixle_pde.verification.capability_inventory.CAPABILITY_INVENTORY",
        "modules": [profile.as_dict() for profile in CAPABILITY_INVENTORY],
    }


def write_capability_matrix(path: str | Path) -> Path:
    """Write the current inventory to ``path`` as byte-stable, sorted-key JSON. Returns the path written."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(to_capability_matrix(), indent=2, sort_keys=True) + "\n"
    target.write_text(payload)
    return target
